// Builds art/tokens.css and art/palettes.js from art/palettes.json (the single source of truth).
// Run from the repo root:  node tools/build-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';

var P = JSON.parse(readFileSync('art/palettes.json', 'utf8'));
var HEAD = '/* GENERATED by tools/build-art.mjs from art/palettes.json. Do not edit by hand. */\n';

function decl(obj, prefix) {
  return Object.keys(obj).filter(function (k) { return k !== '_'; })
    .map(function (k) { return '  --' + prefix + k + ': ' + obj[k] + ';'; }).join('\n');
}

var css = HEAD +
  '@import url("' + P.fonts.import + '");\n\n' +
  ':root {\n' + decl(P.world, 'w-') + '\n' +
  '  --u-display: ' + P.fonts.display + ';\n  --u-body: ' + P.fonts.body + ';\n  --u-hand: ' + P.fonts.hand + ';\n' +
  '  --u-r-card: 34px; --u-r-pill: 999px; --u-ring: 5px;\n}\n\n';

Object.keys(P.places).forEach(function (id) {
  var pl = P.places[id], sel = '[data-place="' + id + '"]';
  css += '/* ' + pl.name + ': ' + pl.mood + ' */\n' + sel + ' {\n' + decl(pl.light, '') + '\n}\n';
  css += '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) ' + sel + ', :root:not([data-theme="light"])' + sel + ' {\n' +
    decl(pl.dark, '').replace(/^/gm, '  ') + '\n  }\n}\n';
  css += '[data-theme="dark"] ' + sel + ', [data-theme="dark"]' + sel + ' {\n' + decl(pl.dark, '') + '\n}\n\n';
});

Object.keys(P.areas || {}).forEach(function (id) {
  var ar = P.areas[id];
  css += '/* area ' + ar.name + ' (a boat\'s own tint inside Tripwrights) */\n[data-area="' + id + '"] {\n' + decl(ar.light, '') + '\n}\n';
});
css += '\n';
css += readFileSync('art/components.css', 'utf8');
writeFileSync('art/tokens.css', css);

writeFileSync('art/palettes.js',
  HEAD + '(function (w) { \'use strict\'; w.UART = w.UART || {}; w.UART.palettes = ' + JSON.stringify({ world: P.world, places: P.places, areas: P.areas }) + '; })(window);\n');
console.log('wrote art/tokens.css and art/palettes.js');
